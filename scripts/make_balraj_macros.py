#!/usr/bin/env python
"""Turn Balraj's results/*.json into paper macros for sections 3/4.2/5.2.

Balraj Singh (24BCE0531) — runbook s7 (D12-D14): "all numbers auto-generated,
nothing hand-typed". Writes paper/sections/balraj_macros.tex. Any absent
artifact yields a __TBD__ macro plus a warning — never a fabricated number.

Usage: python scripts/make_balraj_macros.py
"""
from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def _j(path):
    p = ROOT / path
    if not p.exists():
        return None
    return json.loads(p.read_text())


def _f(x, nd=3):
    return f"{x:.{nd}f}"


def main() -> int:
    gate2 = _j("results/ao/gate2_report.json")
    quir = _j("results/unfold/quantization_bits.json")
    csi = _j("results/unfold/csi_robustness.json")
    gen = _j("results/unfold/generalization.json")
    unf = _j("results/unfold/unfolding_rate_seed0_metrics.json")

    lines = [
        "% Auto-generated by scripts/make_balraj_macros.py — do NOT hand-edit.",
        "% Balraj Singh (24BCE0531); consumed by paper/sections/sec5_2_*.tex.",
    ]
    missing = []

    def add(name, val, warn_ctx):
        if val is None:
            lines.append(f"\\newcommand{{\\{name}}}{{\\textbf{{__TBD__}}}}")
            missing.append(f"{name} (needs {warn_ctx})")
        else:
            lines.append(f"\\newcommand{{\\{name}}}{{{val}}}")

    if gate2:
        add("AoRandomRatio", _f(gate2["ao"]["ratio_ao_random"]), "run_gate2.py")
        add("AoRateMean", _f(gate2["ao"]["rate_mean"]), "run_gate2.py")
        add("AoSD", _f(gate2["ao"]["rate_sd"]), "run_gate2.py")
        add("AoIterMean", f"{gate2['ao']['iterations_mean']:.0f}", "run_gate2.py")
        add("AoWallMeanMs", _f(1e3 * gate2["ao"]["wall_s_per_channel"]["mean"], 0), "run_gate2.py")
        add("GateTwoVerdict", "passed" if gate2["gate2_pass"] else "FAILED",
            "run_gate2.py")
    else:
        for m in ["AoRandomRatio", "AoRateMean", "AoSD", "AoIterMean",
                  "AoWallMeanMs", "GateTwoVerdict"]:
            add(m, None, "scripts/run_gate2.py (results/ao/gate2_report.json)")

    if unf:
        add("UnfoldGapToAo", None, "needs AO reference + unfold metrics post-processing")
    else:
        add("UnfoldGapToAo", None, "scripts/train_unfolding.py (unfolding_rate metrics)")

    if quir:
        for method, by in quir["methods"].items():
            for b, rates in by.items():
                import numpy as _np

                add(f"Q{method}B{b}", _f(float(_np.mean(rates))), "run_robustness.py")
    if csi:
        for eps, entry in csi["eps"].items():
            tag = eps.replace("0.", "p").replace("0p0", "zero")
            add(f"CsiAo{tag}", _f(entry["ao_mean"]), "run_robustness.py")
    if gen:
        import numpy as _np

        for m, rates in gen["gen"].items():
            if rates:
                add(f"Gen{m.capitalize()}", _f(float(_np.mean(rates))),
                    "run_generalization.py")

    target = ROOT / "paper" / "sections" / "balraj_macros.tex"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines) + "\n")
    print(f"wrote {target.relative_to(ROOT)}")
    if missing:
        print("WARNING - __TBD__ macros outstanding (honesty rule: no invented numbers):")
        for m in missing:
            print("  -", m)
    return 0


if __name__ == "__main__":
    sys.exit(main())
